#!/usr/bin/env python3
"""Generates hlpp/src/hlpp_ops.h# (opcode constants) and the `let op_x: int = ...` prelude used by the VM.
Single source of truth for the HLPB instruction set. Run: python3 tools/gen_ops.py"""
OPS = [
 ("halt","stop"),("lit","push lits[a]"),("var","push value of var slot a"),("dyn","pop name, push var value"),
 ("cat","concat top a strings"),("print","pop, print line"),("printlit","print lits[a] line"),
 ("set","pop -> var a, type b"),("setlit","var a = lits[b], type c"),
 ("jmp","pc = a"),("jifok","if last_exit==0 pc=a"),("jiferr","if last_exit!=0 pc=a"),
 ("jtrue","if flag pc=a"),("jfalse","if !flag pc=a"),
 ("exec","pop cmd; run mode a; b=1 check echo"),("execcap","pop cmd; run mode a; stdout -> var b"),
 ("quick","pop args; quick fn lits[a]"),("quickcap","pop args; quick fn lits[a] -> var b"),
 ("builtin","pop line; coreutils"),("builtincap","pop line; coreutils -> var a"),
 ("nbeg","reset numeric stack"),("nlit","push number lits[a]"),("nvar","push number of var a"),
 ("nbin","binary op a (+-*/%)"),("nneg","negate top"),("nend","store numeric result: var a (-1 print), b = lit of source expr"),
 ("nendf","numeric result -> field lits[b] of object var a"),("nfld","push number of field lits[b] of obj var a"),
 ("call","call function lits[a]"),("ret","return"),("deffunc","define function lits[a], body follows, skip to b"),
 ("defarena","define arena function lits[a] size lits[c], skip to b"),("callarena","pop args; call arena fn lits[a]"),
 ("forinit","pop list string; push iteration frame"),("fornext","next item -> var a or jump b"),("forend","pop iteration frame"),
 ("cond","pop string; flag = hl condition"),("cmpv","flag = cmp(a=op, b=operand, c=operand)"),("cmps","pop two strings; flag = cmp op a"),
 ("whinit","push loop counter"),("whtick","count iteration; error past limit"),("whend","pop loop counter"),
 ("swbeg","pop subject -> switch stack"),("swcmp","if subject==lits[a] pc=b"),("swcmpi","if subject==interpolated pop pc=b"),("swend","pop switch stack"),
 ("rptinit","push repeat counter a"),("rptnext","dec; if zero pc=a"),("rptend","pop repeat counter"),
 ("export","pop -> var a + setenv"),("dep","dependency lits[a] apt lits[b]"),
 ("import","import lits[a] detail lits[b] has c"),("fileimport","pop path; detail lits[a] has b"),("dirimport","pop path"),
 ("gobeg","goroutine lits[a]"),("goend","end goroutine"),("chandecl","channel lits[a]"),("chanop","print channel lits[a]"),
 ("bg","pop cmd; background"),("hsh","pop cmd; hsh -c"),("hos","pop args; hackeros tool lits[a]"),
 ("extern","extern def: file lits[a] runtime lits[b]; body follows, skip to c"),("externend","end extern body"),
 ("varprint","print var a"),("nop","nothing"),("dyn_set","pop value,pop name -> var"),
 ("classdef","class lits[a] parent lits[b]"),("defmeth","method lits[a] of current class, skip to b, params lits[c]"),
 ("new","pop args; new object class lits[a] -> var b"),("mcall","pop args; obj var a method lits[b] ; c=1 result->next op var"),
 ("fget","pop objstr; push field lits[a]"),("fset","pop value; obj var a field lits[b]"),("delete","delete object var a"),
 ("mret","store method return value into var a"),("setret","pop -> _ret"),
 ("ashell","pop expr string; shell arithmetic; push result"),("fielddef","class field default: lits[a]=lits[b] type c"),("loopmark","unused"),("exit","pop code; exit"),("sleepnop","nop"),
]
out = [";; GENERATED by tools/gen_ops.py — do not edit.\n;; HLPB instruction set (4 ints per instruction: op a b c)\n"]
for i,(n,d) in enumerate(OPS):
    out.append(f"pub fn op_{n}() -> int is return {i} end   ;; {d}\n")
out.append("\npub fn op_count() -> int is return %d end\n" % len(OPS))
out.append("\npub fn op_name(op: int) -> string is\n")
for i,(n,d) in enumerate(OPS):
    out.append(f"    if op == {i} is return \"{n}\" end\n")
out.append("    return \"?\"\nend\n")
open("hlpp/src/hlpp_ops.h#","w").write("".join(out))
pre = ["    ;; GENERATED prelude (tools/gen_ops.py)\n"]
for i,(n,d) in enumerate(OPS):
    pre.append(f"    let o_{n}: int = {i}\n")
open("tools/ops_prelude.txt","w").write("".join(pre))
print(len(OPS),"ops")

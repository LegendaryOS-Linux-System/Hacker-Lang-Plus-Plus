#!/usr/bin/env python3
"""Generate hlpp/src/hlpp_stdlib.h# (embedded main-libs) from a directory of *.hl files.
usage: gen_stdlib.py <main-libs dir> > hlpp/src/hlpp_stdlib.h#"""
import sys, os
d = sys.argv[1]
def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "").replace("\t", "\\t").replace("{", "\\u{7b}").replace("}", "\\u{7d}")
print(";; GENERATED by tools/gen_stdlib.py — do not edit. Embedded copies of Hacker Lang main-libs.")
print("pub fn source(name: string) -> string is")
for f in sorted(os.listdir(d)):
    if f.endswith(".hl"):
        n = f[:-3]
        body = open(os.path.join(d, f), encoding="utf-8").read()
        print(f'    if name == "{n}" is return "{esc(body)}" end')
print('    return ""')
print("end")
